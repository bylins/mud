/**
\file translit_koi8.cpp - a part of the Bylins engine.
\brief Reducing text to what KOI8-R can actually represent (issue #3681).

Legacy clients speak KOI8-R, CP866 or Windows-1251, and all of those are reached through
KOI8-R. When the engine runs on UTF-8 the text may contain characters none of them has -- a
typographic dash, curly quotes, an accented Latin letter, an emoji. Dropping such a character
to a single placeholder loses information that a reader could still have used, so this table
maps each one to the closest thing KOI8-R does have ("--", '"', "e", "..."), and only what has
no sensible equivalent falls back to the placeholder.

The table is generated, not written by hand: every entry was checked against the KOI8-R codec
to be genuinely absent from it, and the Latin replacements come from Unicode NFKD with the
combining marks stripped. Replacements are UTF-8, because the substitution happens before the
conversion, and are spelled as \xNN escapes so they do not depend on this file's encoding.
*/

