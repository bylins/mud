const char *TranslitToKoi8(char32_t code_point) {
	const auto *end = kTable + std::size(kTable);
	const auto *it = std::lower_bound(kTable, end, code_point,
		[](const TranslitEntry &entry, char32_t value) { return entry.code_point < value; });
	return (it != end && it->code_point == code_point) ? it->replacement : nullptr;
}

std::string Utf8ToKoi8(const std::string &text) {
	if (text.empty()) {
		return text;
	}
	std::string reduced;
	reduced.reserve(text.size());
	for (std::size_t pos = 0; pos < text.size();) {
		char32_t cp = 0;
		const std::size_t len = utf8::decode(text, pos, cp);
		if (len == 0) {
			break;
		}
		const char *const replacement = TranslitToKoi8(cp);
		if (replacement != nullptr) {
			reduced.append(replacement);
		} else {
			reduced.append(text, pos, len);
		}
		pos += len;
	}

	// KOI8-R is never longer than the UTF-8 it came from, so the input size is a safe bound.
	std::vector<char> out(reduced.size() + 1, '\0');
	utf8_to_koi(const_cast<char *>(reduced.c_str()), out.data());
	return std::string(out.data());
}

