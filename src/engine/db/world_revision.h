#ifndef BYLINS_SRC_ENGINE_DB_WORLD_REVISION_H_
#define BYLINS_SRC_ENGINE_DB_WORLD_REVISION_H_

#include <string>

/*
 * Ревизия выложенного мира и его расхождение с ней.
 *
 * Мир -- отдельный репозиторий, и выкладывается он НЕЗАВИСИМО от сборки движка:
 * один и тот же бинарь за свою жизнь видит несколько ревизий мира, а правка из
 * OLC меняет мир вообще без коммита. Поэтому ревизию мира нельзя впечатать в
 * бинарь, как движковую (tools/meson/generate_version.py) -- она читается при
 * старте из каталога мира, который к тому моменту уже известен.
 *
 * Одна ревизия после первой же правки из OLC начинает врать, поэтому рядом с ней
 * ведётся список зон, записанных на диск с момента старта: ревизия говорит, что
 * выложили, список -- что с тех пор разошлось. Список живёт в памяти, то есть
 * ровно один аптайм; правки, сделанные до перезапуска, в нём не всплывут.
 */
namespace world_revision {

// Прочитать ревизию: сперва из <world_dir>/.git, а если git там нет -- первая
// строка <world_dir>/REVISION (её кладёт выкладка). Зовётся один раз при старте.
void Load(const std::string &world_dir);

// "b047e9a22 (master)", "b047e9a22" или строка из REVISION. Пусто, если ревизию
// узнать не удалось -- тогда её просто не показываем, это не ошибка.
[[nodiscard]] const std::string &Get();

// Зона записана на диск. Зовётся из пишущей части источника мира, поэтому сюда
// попадает и правка из OLC, и "oedit save all", и resync -- всё, что разводит
// файлы мира с ревизией. `what` -- что именно записали: "комнаты", "мобы", ...
void NoteZoneSaved(int zone_vnum, const char *what);

// "778 (комнаты, 26.11 10:05), 112 (мобы, 26.11 10:41)". Пусто, если с момента
// старта мир на диск не писали.
[[nodiscard]] std::string FormatEdits();

}  // namespace world_revision

#endif  // BYLINS_SRC_ENGINE_DB_WORLD_REVISION_H_

